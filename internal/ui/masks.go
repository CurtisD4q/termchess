// Hand-tuned silhouettes for the 8×4 square. '#' is the piece. '.' is the
// square. There is no second ink. A quadrant cell is 2×2 samples, so the
// bitmap is 16×8. A sextant cell is 2×3, so that bitmap is 16×12. The first
// and last cell of every row stay empty. Octants repeat the middle sextant
// sample. The king is the only piece that touches the top sample row.

func maskRows(pt chess.PieceType, detail BlockDetail, cellW, cellH int) []string {
	if cellW != sizeW || cellH != sizeH {
		return nil
	}
	var rows []string
	if detail == BlockQuadrant {
		rows = quad[pt]
	} else {
		rows = sext[pt]
	}
	if detail == BlockOctant {
		return expandOctant(rows)
	}
	return rows
}

// expandOctant turns each group of three sextant rows into four octant rows.
func expandOctant(rows []string) []string {
	if len(rows)%3 != 0 {
		return rows
	}
	out := make([]string, 0, len(rows)/3*4)
	for i := 0; i < len(rows); i += 3 {
		out = append(out, rows[i], rows[i+1], rows[i+1], rows[i+2])
	}
	return out
}


func maskFor(style PieceStyle, pt chess.PieceType) []string {
	var set map[chess.PieceType][]string
	switch style {
	case PieceSet1:
		set = pieceSet1
	case PieceSet2:
		set = pieceSet2
	case PieceSet3:
		set = pieceSet3
	case PieceSet4:
		set = pieceSet4
	case PieceSet5:
		set = pieceSet5
	}
	if set != nil {
		if rows := set[pt]; rows != nil {
			return rows
		}
	}
	return classicMask[pt]
}

// pieceSetByStyle returns an alternate set, or nil for classic and silhouette.
func pieceSetByStyle(style PieceStyle) map[chess.PieceType][]string {
	switch style {
	case PieceSet1:
		return pieceSet1
	case PieceSet2:
		return pieceSet2
	case PieceSet3:
		return pieceSet3
	case PieceSet4:
		return pieceSet4
	case PieceSet5:
		return pieceSet5
	default:
		return nil
	}
}
